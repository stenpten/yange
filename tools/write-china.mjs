const noteZh = "示意范围，不是实测国界。"
const noteEn = "Schematic extent, not a surveyed border."

function feature(id, zh, en, points) {
  const ring = points.map(([lon, lat]) => [Math.round(lon * 100) / 100, Math.round(lat * 100) / 100])
  const first = ring[0]
  const last = ring[ring.length - 1]
  if (first[0] !== last[0] || first[1] !== last[1]) ring.push(first)
  let x = 0
  let y = 0
  const n = ring.length - 1
  for (let i = 0; i < n; i++) {
    x += ring[i][0]
    y += ring[i][1]
  }
  return {
    type: "Feature",
    properties: {
      id,
      name_zh: zh,
      name_en: en,
      note_zh: noteZh,
      note_en: noteEn,
      lng: Math.round((x / n) * 100) / 100,
      lat: Math.round((y / n) * 100) / 100,
    },
    geometry: { type: "Polygon", coordinates: [ring] },
  }
}

